  function detectLocale() {
    const stored = window.localStorage.getItem('pc_locale');
    if (stored && SUPPORTED_LOCALES.includes(stored)) return stored;
    const nav = (window.navigator.language || 'en');
    // Match exact (pt-BR) or language prefix (en, de, es, fr, zh, ja)
    if (SUPPORTED_LOCALES.includes(nav)) return nav;
    const prefix = nav.split('-')[0];
    if (SUPPORTED_LOCALES.includes(prefix)) return prefix;
    return 'en';
  }

  let currentLocale = detectLocale();

  function t(key, ...args) {
    const dict = STRINGS[currentLocale] || STRINGS.en;
    let str = dict[key] || STRINGS.en[key] || key;
    if (args.length) {
      // Substitute positional %1$s, %2$s, … placeholders.
      str = str.replace(/%(\d+)\$s/g, (_, idx) => {
        const i = parseInt(idx, 10) - 1;
        return (i >= 0 && i < args.length && args[i] !== undefined && args[i] !== null)
          ? String(args[i]) : '';
      });
    }
    // Collapse the printf-escape `%%` to a literal `%` (must run AFTER
    // positional substitution above, otherwise we'd eat `%1` etc.).
    str = str.replace(/%%/g, '%');
    return str;
  }

  function applyI18n(root) {
    const scope = root || document;
    scope.querySelectorAll('[data-i18n]').forEach((el) => {
      el.textContent = t(el.getAttribute('data-i18n'));
    });
    scope.querySelectorAll('[data-i18n-html]').forEach((el) => {
      el.innerHTML = t(el.getAttribute('data-i18n-html'));
    });
    scope.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
      el.setAttribute('placeholder', t(el.getAttribute('data-i18n-placeholder')));
    });
    scope.querySelectorAll('[data-i18n-title]').forEach((el) => {
      el.setAttribute('title', t(el.getAttribute('data-i18n-title')));
    });
    if (root === document || !root) {
      document.documentElement.setAttribute(
        'lang',
        currentLocale === 'pt-BR' ? 'pt-BR' : currentLocale,
      );
    }
  }

  function setLocale(loc) {
    if (!SUPPORTED_LOCALES.includes(loc) && loc !== '') return;
    if (loc === '') {
      window.localStorage.removeItem('pc_locale');
      currentLocale = detectLocale();
    } else {
      window.localStorage.setItem('pc_locale', loc);
      currentLocale = loc;
    }
    applyI18n();
  }

